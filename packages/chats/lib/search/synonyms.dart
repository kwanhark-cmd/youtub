/// "비슷한 말도 찾기"에 쓰는 낱말 묶음. 한 묶음 안의 낱말은 서로 바꿔 찾습니다.
class Synonyms {
  static const groups = <List<String>>[
    ['앱', '어플', '애플리케이션', '어플리케이션', 'app', '프로그램'],
    ['유튜브', 'youtube', '유투브', '영상 채널'],
    ['영상', '동영상', '비디오', 'video', '쇼츠'],
    ['대본', '스크립트', '시나리오', 'script', '원고'],
    ['주식', '증권', '종목', '투자'],
    ['분할 매수', '나눠 사기', '분할매수', '스플릿'],
    ['여행', '휴가', '여정', '관광'],
    ['일정', '스케줄', '계획', '플랜'],
    ['식단', '식사', '메뉴', '음식'],
    ['운동', '헬스', '체조', '스트레칭'],
    ['블로그', '포스팅', '글쓰기', '게시글'],
    ['엑셀', 'excel', '스프레드시트', '표 계산'],
    ['가계부', '지출 기록', '용돈 기록'],
    ['오류', '에러', '버그', 'error', '문제'],
    ['사진', '이미지', '그림', '썸네일'],
    ['코드', '코딩', '프로그래밍'],
    ['아이폰', 'iphone', 'ios'],
    ['안드로이드', 'android', '갤럭시'],
    ['돈', '비용', '가격', '금액'],
    ['이메일', '메일', 'email', '편지'],
  ];

  static List<String> expand(String word) {
    final w = word.toLowerCase();
    final out = <String>{word};
    for (final g in groups) {
      if (g.any((e) => e.toLowerCase() == w)) out.addAll(g);
    }
    return out.toList();
  }
}
